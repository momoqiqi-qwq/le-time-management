#!/usr/bin/env node
// 单一事实源：桌面课程表模型 + RSS 纯解析器。小程序只生成适配模块，不维护第二份算法。
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const ROOT = path.resolve(__dirname, "..");
function section(source, begin, end) {
  const at = source.indexOf(begin), until = source.indexOf(end, at + begin.length);
  if (at < 0 || until < 0) throw new Error("小程序模型生成标记失效：" + begin);
  return source.slice(at, until).trim() + "\n";
}
function header(file, text) {
  return "// Generated by tools/sync-miniprogram-models.js; do not edit.\n// Source: " + file + "\n// SHA256: " + crypto.createHash("sha256").update(text).digest("hex") + "\n";
}
function sync(options = {}) {
  const schedulePath = "le-time-management/public/plugins/shiguang-schedule/model.js";
  const rssPath = "le-time-management/public/plugins/rss-reader/main.js";
  const schedule = fs.readFileSync(path.join(ROOT, schedulePath), "utf8").replace(/\r\n/g, "\n");
  const rss = fs.readFileSync(path.join(ROOT, rssPath), "utf8").replace(/\r\n/g, "\n");
  const parser = section(rss, "  const DEFAULT_FEEDS =", "  const state =")
    + section(rss, "  function esc(s)", "  /* 二次确认与输入")
    + section(rss, "  function hashId(s)", "  /* ═══════════════ 存储");
  const outputs = {
    "miniprogram/core/scheduleModel.js": header(schedulePath, schedule) + schedule.trimEnd() + "\n",
    "miniprogram/core/rssModel.js": header(rssPath, rss) + parser
      + "module.exports = { DEFAULT_FEEDS, SUGGESTED_FEEDS, FEED_COLORS, normalizeFeedUrl, absolutize, hostOf, hashId, parseFeed, parseDateAny, toText, discoverFeedUrls, looksLikeFeed };\n",
  };
  for (const name of ["LICENSE", "SHIGUANG-WAREHOUSE-LICENSE", "NOTICE.md"]) {
    outputs["miniprogram/licenses/shiguang-schedule/" + name] = fs.readFileSync(path.join(ROOT,"le-time-management/public/plugins/shiguang-schedule",name),"utf8").replace(/\r\n/g,"\n");
  }
  const stale = [];
  for (const [relative, content] of Object.entries(outputs)) {
    const target = path.join(ROOT, relative);
    if (options.check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content) stale.push(relative);
    } else { fs.mkdirSync(path.dirname(target), { recursive:true }); fs.writeFileSync(target, content, "utf8"); }
  }
  if (stale.length) throw new Error("小程序生成模型未同步：" + stale.join("、") + "；请运行 node tools/sync-miniprogram-models.js");
  return Object.keys(outputs);
}
if (require.main === module) {
  try { sync({ check: process.argv.includes("--check") }); console.log("✓ 小程序课程表 / RSS 模型与桌面事实源一致"); }
  catch (e) { console.error(e.message); process.exitCode = 1; }
}
module.exports = { sync };
